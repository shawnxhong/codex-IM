"""Render ``$CODEX_HOME/config.toml`` for the agent container from env (design D4, D13, auth.md).

Stdlib only (the agent image installs codex-im without dependencies). The CODEX_HOME volume is owned by
codex-IM, never the host's ~/.codex, so the whole file is generated.

Env:
  CODEX_IM_DEFAULT_MODEL            optional default model
  CODEX_IM_FORCED_LOGIN_METHOD      optional: chatgpt | api
  CODEX_IM_PROVIDER_IDS             comma list of custom provider ids, e.g. "custom,openai-apikey"
  CODEX_IM_PROVIDER_<ID>_BASE_URL   required per provider (ID upper-cased, '-' -> '_')
  CODEX_IM_PROVIDER_<ID>_ENV_KEY    env var holding the key (default CODEX_IM_PROVIDER_<ID>_API_KEY)
  CODEX_IM_PROVIDER_<ID>_NAME       display name (default: the id)
"""

from __future__ import annotations

import json
import os
import re
import sys
import tempfile
from collections.abc import Mapping

RESERVED_PROVIDER_IDS = frozenset(
    {"openai", "amazon-bedrock", "amazon-bedrock-runtime", "gcp", "ollama", "ollama-chat", "lmstudio"}
)
_ID_RE = re.compile(r"^[a-z0-9][a-z0-9_-]{0,63}$")


class AgentConfigError(ValueError):
    pass


def _q(value: str) -> str:
    """TOML basic string (JSON string escapes are valid TOML basic-string escapes)."""
    return json.dumps(value, ensure_ascii=False)


def _env_prefix(provider_id: str) -> str:
    return "CODEX_IM_PROVIDER_" + provider_id.upper().replace("-", "_")


def render(env: Mapping[str, str]) -> str:
    lines = [
        "# Generated by codex-im (agent entrypoint) at every container start. Do not edit;",
        "# change the agent container's environment instead.",
        'approval_policy = "never"',
        'sandbox_mode = "danger-full-access"',
        'cli_auth_credentials_store = "file"',
    ]
    model = (env.get("CODEX_IM_DEFAULT_MODEL") or "").strip()
    if model:
        lines.append(f"model = {_q(model)}")
    forced = (env.get("CODEX_IM_FORCED_LOGIN_METHOD") or "").strip().lower()
    if forced:
        if forced not in {"chatgpt", "api"}:
            raise AgentConfigError("CODEX_IM_FORCED_LOGIN_METHOD must be 'chatgpt' or 'api'")
        lines.append(f"forced_login_method = {_q(forced)}")
    lines += [
        "",
        "[features]",
        "# D13: blocking request_user_input cannot be answered through the public SDK; keep it off.",
        "default_mode_request_user_input = false",
    ]
    ids = [p.strip() for p in (env.get("CODEX_IM_PROVIDER_IDS") or "").split(",") if p.strip()]
    for provider_id in ids:
        if not _ID_RE.match(provider_id):
            raise AgentConfigError(f"invalid provider id {provider_id!r}")
        if provider_id in RESERVED_PROVIDER_IDS:
            raise AgentConfigError(f"provider id {provider_id!r} is reserved by codex; pick another name")
        prefix = _env_prefix(provider_id)
        base_url = (env.get(f"{prefix}_BASE_URL") or "").strip()
        if not base_url:
            raise AgentConfigError(f"{prefix}_BASE_URL is required")
        env_key = (env.get(f"{prefix}_ENV_KEY") or f"{prefix}_API_KEY").strip()
        name = (env.get(f"{prefix}_NAME") or provider_id).strip()
        lines += [
            "",
            f"[model_providers.{provider_id}]",
            f"name = {_q(name)}",
            f"base_url = {_q(base_url)}",
            f"env_key = {_q(env_key)}",
            '# Codex only supports the Responses API (wire_api = "chat" was removed).',
            'wire_api = "responses"',
        ]
    return "\n".join(lines) + "\n"


def write(codex_home: str, content: str) -> str:
    os.makedirs(codex_home, exist_ok=True)
    path = os.path.join(codex_home, "config.toml")
    fd, tmp = tempfile.mkstemp(prefix=".config.", dir=codex_home)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write(content)
        os.chmod(tmp, 0o600)
        os.replace(tmp, path)
    except BaseException:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise
    return path


def main() -> int:
    codex_home = os.environ.get("CODEX_HOME") or os.path.expanduser("~/.codex")
    try:
        path = write(codex_home, render(os.environ))
    except AgentConfigError as exc:
        print(f"agent config error: {exc}", file=sys.stderr)
        return 2
    print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
